class ArthimeticExample{
	public static void main(String args[]){

		int x=5;
		int y=2;  
		

		//int/int=int 
		//int/double=double
		//double/int = double
		//double/double = double

		System.out.println(x+y);
		System.out.println(x-y);
		System.out.println(x*y);
		System.out.println(x/y);
		System.out.println(x%y);

		double res= x/y;
		System.out.println(res);
		System.out.println(5.0/2);
	}
}